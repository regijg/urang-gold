-- Validates that a location belongs to the store (and tenant) and is active.
create or replace function public.gold_check_location(p_tenant_id uuid, p_store_id uuid, p_location_id uuid)
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if p_location_id is null then return; end if;
  if not exists (
    select 1 from public.gold_locations
    where id = p_location_id and tenant_id = p_tenant_id and store_id = p_store_id and is_active
  ) then
    raise exception 'INVALID_LOCATION' using errcode = '22023';
  end if;
end;
$$;

-- -----------------------------------------------------------------------------
-- Internal: create pieces (used by receive RPC now, purchase/buyback RPCs later).
-- p_items: [{ gross_weight, stone_weight?, serial_number?, cost_price?, name?,
--             category_id?, purity_id?, stone_type?, labor_cost?, stone_price?, margin_amount? }]
-- Values not given fall back to the product (when p_product_id is set).
-- -----------------------------------------------------------------------------
create or replace function public.gold_inventory_create_pieces(
  p_tenant_id uuid, p_store_id uuid, p_location_id uuid, p_product_id uuid,
  p_items jsonb, p_status text, p_source text, p_movement_type text,
  p_reference_type text, p_reference_id uuid, p_notes text
)
returns setof uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product record;
  v_item jsonb;
  v_id uuid;
  v_gross numeric;
  v_stone numeric;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'NO_ITEMS' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) > 200 then
    raise exception 'TOO_MANY_ITEMS' using errcode = '22023';
  end if;

  perform public.gold_check_location(p_tenant_id, p_store_id, p_location_id);

  if p_product_id is not null then
    select * into v_product from public.gold_products where id = p_product_id and tenant_id = p_tenant_id;
    if not found then
      raise exception 'PRODUCT_NOT_FOUND' using errcode = '22023';
    end if;
  end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_gross := (v_item ->> 'gross_weight')::numeric;
    v_stone := coalesce((v_item ->> 'stone_weight')::numeric, v_product.stone_weight, 0);

    insert into public.gold_inventory (
      tenant_id, store_id, location_id, product_id, category_id, purity_id, barcode, serial_number,
      name, gross_weight, stone_weight, stone_type, cost_price, labor_cost, stone_price, margin_amount,
      status, source, notes, created_by)
    values (
      p_tenant_id, p_store_id, p_location_id, p_product_id,
      coalesce((v_item ->> 'category_id')::uuid, v_product.category_id),
      coalesce((v_item ->> 'purity_id')::uuid, v_product.purity_id),
      public.gold_next_barcode(p_tenant_id),
      nullif(trim(v_item ->> 'serial_number'), ''),
      coalesce(nullif(trim(v_item ->> 'name'), ''), v_product.name),
      v_gross, v_stone,
      coalesce(nullif(trim(v_item ->> 'stone_type'), ''), v_product.stone_type),
      coalesce((v_item ->> 'cost_price')::numeric, v_product.cost_price, 0),
      coalesce((v_item ->> 'labor_cost')::numeric, v_product.labor_cost, 0),
      coalesce((v_item ->> 'stone_price')::numeric, v_product.stone_price, 0),
      coalesce((v_item ->> 'margin_amount')::numeric, v_product.margin_amount, 0),
      p_status, p_source, nullif(trim(p_notes), ''), auth.uid())
    returning id into v_id;

    perform public.gold_log_movement(p_tenant_id, v_id, p_movement_type, 1, v_gross - v_stone, null, v_gross,
      null, p_store_id, null, p_location_id, null, p_status, p_reference_type, p_reference_id, p_notes);
    return next v_id;
  end loop;
end;
$$;

