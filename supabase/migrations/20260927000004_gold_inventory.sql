-- =============================================================================
-- GoldPOS — Phase 4: locations (baki), inventory (one row = one physical piece),
-- inventory movements, barcode.
--
-- Rules
--   * Clients can only SELECT inventory/movements. Every stock change goes through
--     a SECURITY DEFINER RPC that checks tenant + permission + store access, locks
--     the affected rows (FOR UPDATE) and ALWAYS writes a movement + audit log.
--   * A piece carries its own purity/weights/pricing components (copied from the
--     product on receipt, editable) because buyback pieces may have no product.
--   * Barcode: GOLD-000001, unique per tenant, generated by gold_next_sequence.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- gold_locations — baki / slot / gudang / etalase inside a store
-- -----------------------------------------------------------------------------
create table public.gold_locations (
  id         uuid primary key default gen_random_uuid(),
  tenant_id  uuid not null default public.gold_current_tenant_id()
             references public.gold_tenants (id) on delete cascade,
  store_id   uuid not null,
  parent_id  uuid,
  code       text not null check (code ~ '^[A-Z0-9-]{1,20}$'),
  name       text not null check (length(trim(name)) between 1 and 80),
  type       text not null default 'BAKI' check (type in ('BAKI', 'SLOT', 'ETALASE', 'GUDANG')),
  sort_order integer not null default 0,
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, code),
  unique (tenant_id, id),
  unique (tenant_id, store_id, id),
  foreign key (tenant_id, store_id) references public.gold_stores (tenant_id, id) on delete cascade,
  foreign key (tenant_id, store_id, parent_id) references public.gold_locations (tenant_id, store_id, id) on delete restrict,
  check (parent_id is null or parent_id <> id)
);

create index gold_locations_tenant_store_idx on public.gold_locations (tenant_id, store_id, is_active, sort_order);
create index gold_locations_parent_idx on public.gold_locations (parent_id);

create trigger gold_locations_updated_at before update on public.gold_locations
  for each row execute function public.gold_set_updated_at();
create trigger gold_locations_audit after insert or update or delete on public.gold_locations
  for each row execute function public.gold_audit_row('LOCATION');

alter table public.gold_locations enable row level security;
revoke all on public.gold_locations from anon, authenticated;
grant select, insert, update, delete on public.gold_locations to authenticated;

create policy gold_locations_select on public.gold_locations for select to authenticated
  using (tenant_id = public.gold_current_tenant_id() and public.gold_can_access_store(store_id));
create policy gold_locations_insert on public.gold_locations for insert to authenticated
  with check (tenant_id = public.gold_current_tenant_id() and public.gold_can_access_store(store_id)
              and public.gold_has_permission('inventory.manage'));
create policy gold_locations_update on public.gold_locations for update to authenticated
  using (tenant_id = public.gold_current_tenant_id() and public.gold_can_access_store(store_id)
         and public.gold_has_permission('inventory.manage'))
  with check (tenant_id = public.gold_current_tenant_id() and public.gold_can_access_store(store_id));
create policy gold_locations_delete on public.gold_locations for delete to authenticated
  using (tenant_id = public.gold_current_tenant_id() and public.gold_can_access_store(store_id)
         and public.gold_has_permission('inventory.manage'));

