-- Current sell price per AVAILABLE piece (same formula as gold_price_quote, discount 0).
create view public.gold_v_inventory_prices
with (security_invoker = true) as
select
  i.id as inventory_id,
  i.tenant_id,
  r.sell_price as sell_rate,
  round(i.gold_weight * r.sell_price, 0) + i.labor_cost + i.stone_price + i.margin_amount as sell_price
from public.gold_inventory i
left join public.gold_v_current_gold_rates r on r.tenant_id = i.tenant_id and r.purity_id = i.purity_id;

revoke all on public.gold_v_inventory_prices from anon, authenticated;
grant select on public.gold_v_inventory_prices to authenticated;

-- -----------------------------------------------------------------------------
-- Inventory summary for the list filter (count + total gold weight).
-- SECURITY INVOKER: runs under the caller's RLS, so it only sums visible pieces.
-- -----------------------------------------------------------------------------
create or replace function public.gold_inventory_summary(
  p_store_id uuid default null, p_location_id uuid default null, p_status text default null,
  p_category_id uuid default null, p_purity_id uuid default null, p_q text default null
)
returns table (item_count bigint, gold_weight numeric)
language sql
stable
security invoker
set search_path = public
as $$
  select count(*), coalesce(sum(i.gold_weight), 0)
  from public.gold_inventory i
  where (p_store_id is null or i.store_id = p_store_id)
    and (p_location_id is null or i.location_id = p_location_id)
    and (p_status is null or i.status = p_status)
    and (p_category_id is null or i.category_id = p_category_id)
    and (p_purity_id is null or i.purity_id = p_purity_id)
    and (p_q is null or p_q = ''
         or i.barcode ilike '%' || p_q || '%' or i.name ilike '%' || p_q || '%' or i.serial_number ilike '%' || p_q || '%')
$$;

revoke all on function public.gold_inventory_summary(uuid, uuid, text, uuid, uuid, text) from public, anon;
grant execute on function public.gold_inventory_summary(uuid, uuid, text, uuid, uuid, text) to authenticated;
