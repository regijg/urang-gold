-- -----------------------------------------------------------------------------
-- RPC: receive stock (opening stock / manual stock-in). Movement: ADJUSTMENT.
-- Supplier purchases get their own RPC (Phase 8, movement PURCHASE).
-- -----------------------------------------------------------------------------
create or replace function public.gold_inventory_receive(
  p_store_id uuid, p_location_id uuid, p_product_id uuid, p_items jsonb, p_notes text default null
)
returns table (inventory_id uuid, barcode text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant uuid := public.gold_require('inventory.manage', p_store_id);
  v_ids uuid[];
begin
  if p_product_id is null then
    raise exception 'PRODUCT_REQUIRED' using errcode = '22023';
  end if;

  select array_agg(x) into v_ids
  from public.gold_inventory_create_pieces(v_tenant, p_store_id, p_location_id, p_product_id, p_items,
    'AVAILABLE', 'OPENING', 'ADJUSTMENT', 'STOCK_IN', null, coalesce(p_notes, 'Stok masuk')) x;

  perform public.gold_log_audit(v_tenant, 'STOCK_IN', 'inventory', null, null,
    jsonb_build_object('store_id', p_store_id, 'product_id', p_product_id, 'inventory_ids', to_jsonb(v_ids)));

  return query select i.id, i.barcode from public.gold_inventory i where i.id = any (v_ids) order by i.barcode;
end;
$$;

-- -----------------------------------------------------------------------------
-- RPC: transfer pieces to another store/location. Movement: TRANSFER.
-- Only AVAILABLE / BUYBACK / DAMAGED pieces can be moved.
-- -----------------------------------------------------------------------------
create or replace function public.gold_inventory_transfer(
  p_inventory_ids uuid[], p_to_store_id uuid, p_to_location_id uuid, p_notes text default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant uuid := public.gold_require('stock_transfer.manage', p_to_store_id);
  v_item record;
  v_count integer := 0;
begin
  if p_inventory_ids is null or cardinality(p_inventory_ids) = 0 then
    raise exception 'NO_ITEMS' using errcode = '22023';
  end if;
  if cardinality(p_inventory_ids) > 500 then
    raise exception 'TOO_MANY_ITEMS' using errcode = '22023';
  end if;
  if not exists (select 1 from public.gold_stores where id = p_to_store_id and tenant_id = v_tenant and is_active) then
    raise exception 'INVALID_STORE' using errcode = '22023';
  end if;
  perform public.gold_check_location(v_tenant, p_to_store_id, p_to_location_id);

  for v_item in
    select * from public.gold_inventory
    where tenant_id = v_tenant and id = any (p_inventory_ids)
    order by id
    for update
  loop
    if not public.gold_can_access_store(v_item.store_id) then
      raise exception 'STORE_FORBIDDEN' using errcode = '42501';
    end if;
    if v_item.status not in ('AVAILABLE', 'BUYBACK', 'DAMAGED') then
      raise exception 'INVALID_STATUS:%', v_item.barcode using errcode = '22023';
    end if;
    if v_item.store_id = p_to_store_id and v_item.location_id is not distinct from p_to_location_id then
      continue;
    end if;

    update public.gold_inventory set store_id = p_to_store_id, location_id = p_to_location_id where id = v_item.id;

    perform public.gold_log_movement(v_tenant, v_item.id, 'TRANSFER', 0, v_item.gold_weight,
      v_item.gross_weight, v_item.gross_weight, v_item.store_id, p_to_store_id,
      v_item.location_id, p_to_location_id, v_item.status, v_item.status, null, null, p_notes);
    v_count := v_count + 1;
  end loop;

  if v_count = 0 and not exists (select 1 from public.gold_inventory where tenant_id = v_tenant and id = any (p_inventory_ids)) then
    raise exception 'NOT_FOUND' using errcode = '22023';
  end if;

  perform public.gold_log_audit(v_tenant, 'TRANSFER_STOCK', 'inventory', null, null,
    jsonb_build_object('inventory_ids', to_jsonb(p_inventory_ids), 'to_store_id', p_to_store_id,
                       'to_location_id', p_to_location_id, 'moved', v_count));
  return v_count;
end;
$$;

-- -----------------------------------------------------------------------------
-- RPC: change piece status (repair, melt, damaged, lost, buyback -> available ...)
-- Optional new gross weight (e.g. after repair / melting loss).
-- SOLD / RESERVED are set only by sales (Phase 5).
-- -----------------------------------------------------------------------------
create or replace function public.gold_inventory_change_status(
  p_inventory_id uuid, p_to_status text, p_new_gross_weight numeric default null, p_notes text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant uuid := public.gold_require('inventory.manage');
  v_item record;
  v_type text;
  v_new_gross numeric;
begin
  select * into v_item from public.gold_inventory where id = p_inventory_id and tenant_id = v_tenant for update;
  if not found then
    raise exception 'NOT_FOUND' using errcode = '22023';
  end if;
  if not public.gold_can_access_store(v_item.store_id) then
    raise exception 'STORE_FORBIDDEN' using errcode = '42501';
  end if;

  -- allowed transitions -> movement type
  v_type := case
    when v_item.status in ('AVAILABLE', 'BUYBACK', 'DAMAGED') and p_to_status = 'REPAIR' then 'REPAIR_OUT'
    when v_item.status = 'REPAIR' and p_to_status in ('AVAILABLE', 'DAMAGED') then 'REPAIR_IN'
    when v_item.status in ('AVAILABLE', 'BUYBACK', 'DAMAGED', 'REPAIR') and p_to_status = 'MELTED' then 'MELT'
    when v_item.status in ('AVAILABLE', 'BUYBACK') and p_to_status = 'DAMAGED' then 'ADJUSTMENT'
    when v_item.status in ('BUYBACK', 'DAMAGED') and p_to_status = 'AVAILABLE' then 'ADJUSTMENT'
    when v_item.status in ('AVAILABLE', 'BUYBACK', 'DAMAGED', 'REPAIR') and p_to_status = 'LOST' then 'ADJUSTMENT'
    when v_item.status = 'LOST' and p_to_status = 'AVAILABLE' then 'ADJUSTMENT'
    else null
  end;
  if v_type is null then
    raise exception 'INVALID_TRANSITION' using errcode = '22023';
  end if;
  if p_to_status in ('LOST', 'DAMAGED', 'MELTED') and coalesce(trim(p_notes), '') = '' then
    raise exception 'NOTES_REQUIRED' using errcode = '22023';
  end if;

  v_new_gross := coalesce(p_new_gross_weight, v_item.gross_weight);
  if v_new_gross <= v_item.stone_weight then
    raise exception 'INVALID_WEIGHT' using errcode = '22023';
  end if;

  update public.gold_inventory set status = p_to_status, gross_weight = v_new_gross where id = v_item.id;

  perform public.gold_log_movement(v_tenant, v_item.id, v_type,
    case when p_to_status in ('LOST', 'MELTED') then -1 when v_item.status = 'LOST' then 1 else 0 end,
    v_new_gross - v_item.stone_weight, v_item.gross_weight, v_new_gross,
    v_item.store_id, v_item.store_id, v_item.location_id, v_item.location_id,
    v_item.status, p_to_status, null, null, p_notes);

  perform public.gold_log_audit(v_tenant, 'ADJUSTMENT', 'inventory', v_item.id::text,
    jsonb_build_object('status', v_item.status, 'gross_weight', v_item.gross_weight),
    jsonb_build_object('status', p_to_status, 'gross_weight', v_new_gross, 'notes', p_notes));
end;
$$;

-- -----------------------------------------------------------------------------
-- RPC: edit non-stock details of a piece (name, serial, pricing components, notes)
-- No movement (stock unchanged) but audited.
-- -----------------------------------------------------------------------------
create or replace function public.gold_inventory_update_details(
  p_inventory_id uuid, p_name text, p_serial_number text, p_stone_type text,
  p_cost_price numeric, p_labor_cost numeric, p_stone_price numeric, p_margin_amount numeric, p_notes text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant uuid := public.gold_require('inventory.manage');
  v_old record;
begin
  select * into v_old from public.gold_inventory where id = p_inventory_id and tenant_id = v_tenant for update;
  if not found then
    raise exception 'NOT_FOUND' using errcode = '22023';
  end if;
  if not public.gold_can_access_store(v_old.store_id) then
    raise exception 'STORE_FORBIDDEN' using errcode = '42501';
  end if;
  if v_old.status in ('SOLD', 'MELTED') then
    raise exception 'INVALID_STATUS' using errcode = '22023';
  end if;

  update public.gold_inventory set
    name = trim(p_name),
    serial_number = nullif(trim(p_serial_number), ''),
    stone_type = nullif(trim(p_stone_type), ''),
    cost_price = p_cost_price,
    labor_cost = p_labor_cost,
    stone_price = p_stone_price,
    margin_amount = p_margin_amount,
    notes = nullif(trim(p_notes), '')
  where id = p_inventory_id;

  perform public.gold_log_audit(v_tenant, 'UPDATE_INVENTORY', 'inventory', p_inventory_id::text,
    to_jsonb(v_old), (select to_jsonb(i) from public.gold_inventory i where i.id = p_inventory_id));
end;
$$;

-- Sell-price quote for a physical piece (uses the piece's own weight/purity/components).
create or replace function public.gold_quote_inventory(p_inventory_id uuid, p_discount numeric default 0)
returns table (inventory_id uuid, rate_id uuid, sell_rate numeric, gold_value numeric,
               subtotal numeric, discount numeric, total numeric)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_tenant uuid := public.gold_current_tenant_id();
  v_i record;
begin
  if v_tenant is null then
    raise exception 'UNAUTHENTICATED' using errcode = '42501';
  end if;
  if not (public.gold_has_permission('inventory.view') or public.gold_has_permission('pos.use')) then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  select * into v_i from public.gold_inventory where id = p_inventory_id and tenant_id = v_tenant;
  if not found or not public.gold_can_access_store(v_i.store_id) then
    return;
  end if;
  return query
  select v_i.id, q.rate_id, q.sell_rate, q.gold_value, q.subtotal, q.discount, q.total
  from public.gold_price_quote(v_tenant, v_i.purity_id, v_i.gold_weight, v_i.labor_cost,
                               v_i.stone_price, v_i.margin_amount, p_discount) q;
end;
$$;

