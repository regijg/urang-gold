-- Resolves the caller and checks permission (+ optional store access). Returns tenant id.
create or replace function public.gold_require(p_permission text, p_store_id uuid default null)
returns uuid
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_tenant uuid := public.gold_current_tenant_id();
begin
  if v_tenant is null then
    raise exception 'UNAUTHENTICATED' using errcode = '42501';
  end if;
  if not public.gold_has_permission(p_permission) then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  if p_store_id is not null and not public.gold_can_access_store(p_store_id) then
    raise exception 'STORE_FORBIDDEN' using errcode = '42501';
  end if;
  return v_tenant;
end;
$$;

